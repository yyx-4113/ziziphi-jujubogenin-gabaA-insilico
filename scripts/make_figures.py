def parse_coords_pdb(path, chain_filter=None, atom_filter=None):
    """Return list of (chain, x, y, z) from ATOM/HETATM lines using fixed cols."""
    pts = []
    with open(path) as fh:
        for line in fh:
            if not (line.startswith("ATOM") or line.startswith("HETATM")):
                continue
            if len(line) < 55:
                continue
            x = float(line[30:38]); y = float(line[38:46]); z = float(line[46:54])
            chain = line[21]
            atom = line[12:16].strip()
            if chain_filter and chain not in chain_filter:
                continue
            if atom_filter and atom not in atom_filter:
                continue
            pts.append((chain, x, y, z))
    return pts

def parse_ligand(path):
    """Parse ligand heavy-atom coords from a .pdb or .pdbqt file."""
    pts = []
    with open(path) as fh:
        for line in fh:
            if not (line.startswith("ATOM") or line.startswith("HETATM")):
                continue
            if len(line) < 55:
                continue
            x = float(line[30:38]); y = float(line[38:46]); z = float(line[46:54])
            pts.append((x, y, z))
    return np.array(pts, dtype=float)

